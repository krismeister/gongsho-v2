# lib/tpl-langchain-api.sh — langchain-api template driver (Node toolchain).
# Sourced via tools/lib.sh; never sourced or run alone. See tpl-goa-api.sh
# for the interface contract and the _T_ locals convention.

tpl_langchain_api_needs_install() { # <template> — 0: node APIs install via pnpm
    return 0
}

tpl_langchain_api_scaffold_api() { # <id> <path> <app> — as-is copy; install comes later
    _T_id=$1; _T_path=$2; _T_app=$3
    log "scaffolded API (langchain-api; run: install $_T_id before build)"
    unset _T_id _T_path _T_app
}

tpl_langchain_api_build_api() { # <id> <app> <bin> <tools-dir> — tsc plus node launcher
    _T_id=$1; _T_app=$2; _T_bin=$3; _T_d=$4
    [ -x "$_T_app/node_modules/.bin/tsc" ] || die "node_modules missing for '$_T_id' (run: install $_T_id)"
    ( cd "$_T_app" && sh "$_T_d/pnpm" exec tsc -b ) || die "typecheck failed (see above)"
    [ -f "$_T_app/dist/main.js" ] || die "typecheck emitted no dist/main.js"
    rm -rf -- "${_T_bin}.new"
    mkdir -p -- "${_T_bin}.new" || die "cannot create build scratch"
    # The launcher runs the deployment's own dist/ plus node_modules in
    # place (vendoring 90M of deps per build would triple every output).
    # The app path is baked in absolute: moving the home root needs a
    # rebuild, same as any compiled output.
    _T_launcher_tmp=$(tmp_in_dir "${_T_bin}.new")
    {
        printf '#!/bin/sh\n# Generated by tools/build: node launcher for the deployment bundle.\n'
        printf 'exec node "%s/dist/main.js" "$@"\n' "$_T_app"
    } >"$_T_launcher_tmp"
    chmod +x -- "$_T_launcher_tmp" || die "cannot chmod launcher"
    atomic_mv "$_T_launcher_tmp" "${_T_bin}.new/api"
    rm -rf -- "$_T_bin" || die "cannot replace old output"
    mv -- "${_T_bin}.new" "$_T_bin" || die "bin promotion failed"
    log "built $_T_bin/api (node launcher)"
    unset _T_id _T_app _T_bin _T_d _T_launcher_tmp
}

tpl_langchain_api_run_e2e() { # <id> <tools-dir> — node --test over the app dir
    _T_id=$1; _T_d=$2
    _T_rc=0
    ( cd "$(app_dir "$_T_id")" && sh "$_T_d/pnpm" run test-e2e ) || _T_rc=$?
    unset _T_id _T_d
    return "$_T_rc"
}

tpl_langchain_api_regen_check() { # <id> <app> <tools-dir> <h1> <h2> — re-typecheck plus spec paths
    _T_id=$1; _T_app=$2; _T_d=$3; _T_h1=$4; _T_h2=$5
    ( cd "$_T_app" && sh "$_T_d/pnpm" exec tsc -b --force ) || die "re-typecheck failed (see above)"
    ( cd "$_T_app" && node -e "const s=require('fs').readFileSync('gen/openapi.json','utf8');const j=JSON.parse(s);for(const p of ['/healthz','/info','/openapi.json']){if(!j.paths[p]){console.error('openapi.json misses '+p);process.exit(1)}}console.log('openapi.json contract paths present')" ) || die "committed spec fails the contract check"
    log "spec/ strictness passed"
    unset _T_id _T_app _T_d _T_h1 _T_h2
}

tpl_langchain_api_cache_warm() { # <pnpm-bin> — prefetch the template deps to the shared store
    _T_pnpm_bin=$1
    _T_ft=$(mktemp -d) || die "cannot create temp dir"
    cp -- "$REPO_ROOT/templates/langchain-api/app/package.json" "$REPO_ROOT/templates/langchain-api/app/pnpm-lock.yaml" "$_T_ft/" || { rm -rf -- "$_T_ft"; die "cannot stage langchain-api manifests"; }
    ( cd "$_T_ft" && "$_T_pnpm_bin" fetch --store-dir "$REPO_ROOT/.cache/pnpm/store" ) || { rm -rf -- "$_T_ft"; die "pnpm fetch failed (see above)"; }
    rm -rf -- "$_T_ft"
    log "langchain-api dependencies prefetched to the shared store"
    unset _T_pnpm_bin _T_ft
}
